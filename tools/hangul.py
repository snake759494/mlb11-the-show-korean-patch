def build_set(used, cap):
    """used(음절 문자 집합) + 우선순위 음절로 cap 개(자모 51 제외)까지 채운 유니코드 정렬 목록."""
    s = set(used)
    order = [ch for ch in NAMES if 0xAC00 <= ord(ch) <= 0xD7A3]
    order += [syl(c, v) for v in VOW for c in range(19)]
    for j in FIN:
        for v in VOW[:12]:
            for c in range(19): order.append(syl(c, v, j))
    for ch in order:
        if len(s) >= cap: break
        s.add(ch)
    return sorted(s)
